local previousMembers
local previousWasRaid = false
local ready = false
local pendingGreetings = {}
local frame = CreateFrame("Frame")

local function sendGreeting()
    local _, class = UnitClass("player")
    local choices = greetings[class]
    if not choices then
        print("|cff00bfffPartyWelcome:|r No greetings available for your class.")
        return
    end
    SendChatMessage(choices[math.random(#choices)], "PARTY")
end

local function updatePending(_, elapsed)
    for identity, remaining in pairs(pendingGreetings) do
        remaining = remaining - elapsed
        if remaining <= 0 then
            pendingGreetings[identity] = nil
            sendGreeting()
        else
            pendingGreetings[identity] = remaining
        end
    end
    if not next(pendingGreetings) then
        frame:SetScript("OnUpdate", nil)
    end
end

local function getMemberIdentity(unit)
    if type(UnitGUID) == "function" then
        local guid = UnitGUID(unit)
        if type(guid) == "string" then
            return guid
        end
    end

    if type(UnitName) == "function" then
        local name, realm = UnitName(unit)
        if type(name) == "string" and name ~= "" then
            return name .. "-" .. (type(realm) == "string" and realm or "")
        end
    end

    return nil
end

local function collectMembers()
    local members = {}
    if type(GetNumGroupMembers) ~= "function" then
        return members, false, false
    end

    local inRaid = type(IsInRaid) == "function" and IsInRaid() or false
    if inRaid then
        return members, false, true
    end

    local groupSize = GetNumGroupMembers()
    if type(groupSize) ~= "number" or groupSize < 2 then
        return members, false, false
    end

    local count = math.min(groupSize - 1, 4)
    local playerGuid = type(UnitGUID) == "function" and UnitGUID("player")

    for index = 1, count do
        local unit = "party" .. index
        local isPlayer = type(UnitIsUnit) == "function" and UnitIsUnit(unit, "player")
        local identity = getMemberIdentity(unit)

        if not isPlayer and identity ~= nil and (playerGuid == nil or identity ~= playerGuid) then
            members[identity] = true
        end
    end

    return members, true, false
end

local function updateRoster(announceNewMembers)
    local members, isParty, inRaid = collectMembers()

    for identity in pairs(pendingGreetings) do
        if not announceNewMembers or not isParty or previousWasRaid or not members[identity] then
            pendingGreetings[identity] = nil
        end
    end

    if announceNewMembers and isParty and not previousWasRaid and previousMembers ~= nil then
        for identity in pairs(members) do
            if not previousMembers[identity] then
                pendingGreetings[identity] = 2
            end
        end
    end

    frame:SetScript("OnUpdate", next(pendingGreetings) and updatePending or nil)
    previousMembers = members
    previousWasRaid = inRaid
end

frame:RegisterEvent("PLAYER_LOGIN")
frame:RegisterEvent("PLAYER_ENTERING_WORLD")
frame:RegisterEvent("GROUP_ROSTER_UPDATE")
frame:SetScript("OnEvent", function(_, event)
    if event == "PLAYER_LOGIN" then
        updateRoster(false)
        return
    end

    if event == "PLAYER_ENTERING_WORLD" then
        updateRoster(false)
        ready = true
        return
    end

    updateRoster(ready)
end)
