local function buildMessages(openers, classLines)
    local messagesByClass = {}
    for class, lines in pairs(classLines) do
        local messages = {}
        for _, opener in ipairs(openers) do
            for _, line in ipairs(lines) do
                messages[#messages + 1] = opener .. " " .. line
            end
        end
        messagesByClass[class] = messages
    end
    return messagesByClass
end

